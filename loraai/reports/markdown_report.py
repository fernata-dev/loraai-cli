"""Markdown reports: readable in a terminal, a PR comment, or a text editor."""

from __future__ import annotations

from typing import List, Optional

from ..analysis.provenance import summary_lines
from ..models import Analysis, CleanResult, HumanizeResult, Severity
from ..sanitize import one_line, redact_secrets
from ..version import get_version


def _table(headers: List[str], rows: List[List[str]]) -> List[str]:
    if not rows:
        return []
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return lines


def render(
    analysis: Analysis,
    *,
    clean: Optional[CleanResult] = None,
    humanize: Optional[HumanizeResult] = None,
) -> str:
    """Render the analysis as Markdown."""
    out: List[str] = []
    source = analysis.source
    stats = analysis.statistics
    synth = analysis.synthetic

    out.append("# loraai report")
    out.append("")
    out.append(f"*Generated by loraai {get_version()}*")
    out.append("")

    # -- source ------------------------------------------------------------
    out.append("## Source")
    out.append("")
    out.extend(
        _table(
            ["Field", "Value"],
            [
                ["Origin", source.origin],
                ["Path", source.path or "-"],
                ["Encoding", source.encoding + (" (BOM)" if source.had_bom else "")],
                ["Content kind", source.content_kind],
                ["Language", source.language],
                ["Characters", f"{source.char_count:,}"],
                ["Words", f"{stats.words:,}"],
                ["Sentences", f"{stats.sentences:,}"],
                ["Paragraphs", f"{stats.paragraphs:,}"],
            ],
        )
    )
    out.append("")

    # -- synthetic ---------------------------------------------------------
    out.append("## Synthetic-text assessment")
    out.append("")
    out.append(f"**{synth.verdict.label}** — score {synth.score:.2f}, "
               f"confidence {synth.confidence:.2f}, reliability {synth.reliability}")
    out.append("")

    if synth.signals:
        rows = [
            [
                s.label,
                "-" if s.value is None else f"{s.value:.3f}",
                f"{s.weight:+.2f}",
                s.direction,
            ]
            for s in sorted(synth.signals, key=lambda x: -abs(x.weight))
        ]
        out.extend(_table(["Signal", "Value", "Weight", "Leans"], rows))
        out.append("")

    if synth.caveats:
        out.append("> **How to read this.** " + " ".join(synth.caveats))
        out.append("")

    # -- provenance --------------------------------------------------------
    out.append("## Provenance marking")
    out.append("")
    out.append("```")
    out.extend(summary_lines(analysis.watermark))
    out.append("```")
    out.append("")
    out.append(
        "> " + analysis.watermark.statistical_watermark["common_misconception"]
    )
    out.append("")
    out.append(
        "> " + analysis.watermark.statistical_watermark["what_does_degrade_it"]
    )
    out.append("")

    # -- unicode -----------------------------------------------------------
    unicode_report = analysis.unicode
    out.append("## Unicode forensics")
    out.append("")
    out.append(
        f"{unicode_report.total} finding(s), highest severity "
        f"**{unicode_report.max_severity.value}**."
    )
    out.append("")

    if unicode_report.payloads:
        out.append("### Hidden payloads decoded")
        out.append("")
        out.extend(
            _table(
                ["Scheme", "Characters", "Decoded"],
                [
                    [p.scheme, str(p.char_count), f"`{one_line(p.decoded, 70)}`"]
                    for p in unicode_report.payloads
                ],
            )
        )
        out.append("")

    if unicode_report.class_counts:
        out.extend(
            _table(
                ["Class", "Count"],
                [[k, str(v)] for k, v in unicode_report.class_counts.items()],
            )
        )
        out.append("")

    high = [
        f for f in unicode_report.findings
        if f.severity.rank >= Severity.HIGH.rank
    ][:25]
    if high:
        out.append("### Highest-severity findings")
        out.append("")
        out.extend(
            _table(
                ["Code", "Name", "Severity", "Line:Col", "Action"],
                [
                    [f.code, f.name, f.severity.value, f"{f.line}:{f.column}",
                     f.recommended_action]
                    for f in high
                ],
            )
        )
        out.append("")

    # -- markers -----------------------------------------------------------
    markers = analysis.markers
    out.append("## AI-writing markers")
    out.append("")
    out.append(
        f"{markers.total} marker(s), {markers.density_per_1k:.1f} per 1000 words "
        f"({markers.weighted_density_per_1k:.1f} severity-weighted)."
    )
    out.append("")
    if markers.hits:
        out.extend(
            _table(
                ["Line", "Category", "Matched", "Suggestion"],
                [
                    [str(h.line), h.category, f"`{one_line(h.matched, 40)}`",
                     h.suggestion or "-"]
                    for h in markers.hits[:30]
                ],
            )
        )
        if len(markers.hits) > 30:
            out.append("")
            out.append(f"*... and {len(markers.hits) - 30} more.*")
        out.append("")

    # -- optional sections -------------------------------------------------
    if clean is not None:
        out.append("## Cleaning")
        out.append("")
        out.append(
            f"Profile **{clean.profile}** — {clean.total_changes} change(s); "
            f"semantics preserved: **{'yes' if clean.semantic_preserved else 'REVIEW'}**."
        )
        out.append("")
        for note in clean.semantic_notes:
            out.append(f"- {note}")
        out.append("")

    if humanize is not None:
        out.append("## Humanization")
        out.append("")
        out.append(
            f"Provider **{humanize.provider}**, style **{humanize.style}**, "
            f"intensity **{humanize.intensity}** — "
            f"markers {humanize.marker_before} → {humanize.marker_after}, "
            f"{len(humanize.edits)} edit(s)."
        )
        out.append("")
        for note in humanize.notes:
            out.append(f"- {note}")
        out.append("")

    if analysis.warnings:
        out.append("## Warnings")
        out.append("")
        for warning in analysis.warnings:
            out.append(f"- {warning}")
        out.append("")

    return redact_secrets("\n".join(out))
